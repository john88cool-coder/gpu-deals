"""Общая для магазинов защита от повторов при обходе страниц.

Каталоги отдают одну и ту же позицию дважды по двум причинам, обе проверены на
живых страницах:

- номер страницы за границей каталога не даёт пустого ответа. У sulpak каталог
  из 5 страниц, а запросы `?page=7`, `?page=9`, `?page=10` возвращают
  `data-currentPage="3"` с теми же 22 карточками — цикл «идём, пока страницы
  отдают позиции» не останавливался никогда;
- товары переставляются между страницами между запросами. У forcecom обход
  страниц 1-10 подряд дал 200 позиций и 194 уникальных названия: шесть товаров
  пришли на двух разных страницах одного обхода.

И то и другое пишет копии одного снимка в историю цен: у позиции sulpak
накопилось 321 наблюдение против 40 у сопоставимой позиции technodom. Медианы
классов это не искажает (`class_prices` группирует по identity), а вот порог
`min_observations_for_trend` набирается копиями за один обход вместо суток.
"""

from __future__ import annotations

from collections.abc import Iterable

from ..models import Offer


def new_offers(offers: Iterable[Offer], seen: set[str]) -> list[Offer]:
    """Позиции с ещё не встречавшимся identity; `seen` пополняется на месте.

    При совпадении identity остаётся позиция, встреченная раньше: страницы
    приходят в порядке сортировки самого магазина, и первая встреча — та, что
    магазин показывает выше.
    """
    fresh: list[Offer] = []
    for offer in offers:
        if offer.identity in seen:
            continue
        seen.add(offer.identity)
        fresh.append(offer)
    return fresh
